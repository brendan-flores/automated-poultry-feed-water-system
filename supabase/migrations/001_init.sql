-- CoopControl Supabase Schema
-- This migration creates the database tables for the poultry feed and water management system

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- Devices table
-- Stores registered ESP32 devices
CREATE TABLE devices (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    -- Unique constraint: one user can have multiple devices, but each device belongs to one user
    CONSTRAINT fk_user FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE
);

-- Device state table
-- Stores the latest state of each device (updated by ESP32)
CREATE TABLE device_state (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    feed_weight_g INTEGER NOT NULL DEFAULT 0,
    hopper_status TEXT NOT NULL CHECK (hopper_status IN ('full', 'low', 'empty', 'error')),
    reservoir_status TEXT NOT NULL CHECK (reservoir_status IN ('ok', 'low', 'error')),
    trough_status TEXT NOT NULL CHECK (trough_status IN ('ok', 'low', 'error')),
    system_state TEXT NOT NULL CHECK (system_state IN ('idle', 'feeding', 'refilling')),
    last_seen TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT fk_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

-- Schedules table
-- Stores feeding schedules for each device
CREATE TABLE schedules (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    time TEXT NOT NULL, -- Format: HH:MM (24-hour)
    target_weight_g INTEGER NOT NULL CHECK (target_weight_g >= 50 AND target_weight_g <= 1000),
    enabled BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT fk_device_schedule FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

-- Commands table
-- Stores commands sent from the app to the device
CREATE TABLE commands (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    type TEXT NOT NULL CHECK (type IN ('feed_now', 'refill_water')),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'rejected', 'done', 'failed')),
    reason TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT fk_device_command FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

-- Alerts table
-- Stores alerts generated by the device
CREATE TABLE alerts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    device_id UUID NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    type TEXT NOT NULL CHECK (type IN (
        'hopper_low',
        'hopper_empty',
        'reservoir_low',
        'feeding_failed',
        'feeding_timeout',
        'pump_timeout',
        'sensor_error',
        'device_offline',
        'device_online',
        'feeding_completed'
    )),
    message TEXT NOT NULL,
    severity TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'critical')),
    read BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),

    CONSTRAINT fk_device_alert FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

-- Create indexes for performance
CREATE INDEX idx_device_state_device_id ON device_state(device_id);
CREATE INDEX idx_device_state_last_seen ON device_state(last_seen);
CREATE INDEX idx_schedules_device_id ON schedules(device_id);
CREATE INDEX idx_schedules_enabled ON schedules(enabled);
CREATE INDEX idx_commands_device_id ON commands(device_id);
CREATE INDEX idx_commands_status ON commands(status);
CREATE INDEX idx_alerts_device_id ON alerts(device_id);
CREATE INDEX idx_alerts_read ON alerts(read);
CREATE INDEX idx_alerts_created_at ON alerts(created_at DESC);

-- Enable Row Level Security (RLS) on all tables
ALTER TABLE devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE device_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE schedules ENABLE ROW LEVEL SECURITY;
ALTER TABLE commands ENABLE ROW LEVEL SECURITY;
ALTER TABLE alerts ENABLE ROW LEVEL SECURITY;

-- RLS Policies for regular users (app users)
-- Users can only access their own devices and related data

-- Devices: Users can read and insert their own devices
CREATE POLICY "Users can view own devices"
    ON devices FOR SELECT
    USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own devices"
    ON devices FOR INSERT
    WITH CHECK (auth.uid() = user_id);

CREATE POLICY "Users can update own devices"
    ON devices FOR UPDATE
    USING (auth.uid() = user_id);

-- Device state: Users can read state of their own devices
CREATE POLICY "Users can view own device state"
    ON device_state FOR SELECT
    USING (
        device_id IN (
            SELECT id FROM devices WHERE user_id = auth.uid()
        )
    );

-- Schedules: Users can read, insert, update, delete schedules for their own devices
