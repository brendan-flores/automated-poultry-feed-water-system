-- RLS Policies for device users (ESP32)
-- Device users have limited access to only their own device's data
-- These policies use a custom claim (device_id) from the JWT token
-- The ESP32 will sign in as a dedicated user with a device_id claim

-- Device state: Device users can read and update only their own device's state
CREATE POLICY "Device users can read own device state"
    ON device_state FOR SELECT
    USING (
        auth.jwt()->>'device_id'::text = device_id::text
    );

CREATE POLICY "Device users can update own device state"
    ON device_state FOR INSERT
    WITH CHECK (
        auth.jwt()->>'device_id'::text = device_id::text
    );

CREATE POLICY "Device users can update existing device state"
    ON device_state FOR UPDATE
    USING (
        auth.jwt()->>'device_id'::text = device_id::text
    );

-- Schedules: Device users can read schedules for their own device
CREATE POLICY "Device users can read own schedules"
    ON schedules FOR SELECT
    USING (
        auth.jwt()->>'device_id'::text = device_id::text
    );

-- Commands: Device users can read and update commands for their own device
