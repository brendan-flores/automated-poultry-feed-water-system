    );

CREATE POLICY "Device users can update own commands"
    ON commands FOR UPDATE
    USING (
        auth.jwt()->>'device_id'::text = device_id::text
    );

-- Alerts: Device users can insert alerts for their own device
CREATE POLICY "Device users can insert own alerts"
    ON alerts FOR INSERT
    WITH CHECK (
        auth.jwt()->>'device_id'::text = device_id::text
    );

-- Create a function to update updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create triggers for auto-updating updated_at
CREATE TRIGGER update_devices_updated_at
    BEFORE UPDATE ON devices
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_device_state_updated_at
    BEFORE UPDATE ON device_state
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_schedules_updated_at
    BEFORE UPDATE ON schedules
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

CREATE TRIGGER update_commands_updated_at
    BEFORE UPDATE ON commands
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();
